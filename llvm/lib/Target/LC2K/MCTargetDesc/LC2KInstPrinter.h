#ifndef LLVM_LIB_TARGET_LC2K_INSTPRINTER_LC2KINSTPRINTER_H
#define LLVM_LIB_TARGET_LC2K_INSTPRINTER_LC2KINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class LC2KInstPrinter : public MCInstPrinter {
public:
  LC2KInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                  const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  // Required to implement MCInstPrinter, autogenerated by TableGen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;

  // Autogenerated by TableGen.
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);

  // Autogenerated by TableGen.
  const char *getRegisterName(MCRegister Reg);

  // Need to override -- see MCInstPrinter.cpp.
  void printRegName(raw_ostream &OS, MCRegister Reg) override;

  // Required for TableGen'erated AsmWriter.
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);

  // Makes printOperand cleaner.
  void printImmediate(raw_ostream &O, int64_t Imm);

  // Required to implement MCInstPrinter.
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &OS) override;
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_LC2K_INSTPRINTER_LC2KINSTPRINTER_H
