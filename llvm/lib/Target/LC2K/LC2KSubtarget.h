#ifndef LLVM_LIB_TARGET_LC2K_LC2KSUBTARGET_H
#define LLVM_LIB_TARGET_LC2K_LC2KSUBTARGET_H

#include "LC2KISelLowering.h"
#include "LC2KInstrInfo.h"
#include "llvm/CodeGen/GlobalISel/CallLowering.h"
#include "llvm/CodeGen/GlobalISel/InstructionSelector.h"
#include "llvm/CodeGen/GlobalISel/LegalizerInfo.h"
#include "llvm/CodeGen/RegisterBankInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/MC/MCInst.h"
#include "llvm/MC/MCInstrInfo.h"

#define GET_SUBTARGETINFO_HEADER
#include "LC2KGenSubtargetInfo.inc"

namespace llvm {

class LC2KSubtarget : public LC2KGenSubtargetInfo {
  virtual void anchor();
  LC2KInstrInfo InstrInfo;
  LC2KFrameLowering FrameLowering;
  LC2KTargetLowering TLInfo;

protected:
  std::unique_ptr<CallLowering> CallLoweringInfo;
  std::unique_ptr<InstructionSelector> InstSelector;
  std::unique_ptr<LegalizerInfo> Legalizer;
  std::unique_ptr<RegisterBankInfo> RegBankInfo;

public:
  LC2KSubtarget(const Triple &TT, const std::string &CPU, const std::string &FS,
                const LC2KTargetMachine &TM);

  // ParseSubtargetFeatures - Parses features string setting specified
  // subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const TargetRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }

  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  const LC2KTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  const TargetInstrInfo *getInstrInfo() const override { return &InstrInfo; }

  const CallLowering *getCallLowering() const override;
  InstructionSelector *getInstructionSelector() const override;
  const LegalizerInfo *getLegalizerInfo() const override;
  const RegisterBankInfo *getRegBankInfo() const override;
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_LC2K_LC2KSUBTARGET_H
